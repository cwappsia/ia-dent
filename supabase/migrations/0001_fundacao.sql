-- Dentia 0001 — Fundação: schema, clinics, members, invites, auditoria
-- 1 migration = 1 transação

create schema if not exists dentia;

-- PostgREST só serve schemas listados em db_schemas (canal dashboard/MCP)
alter role authenticator set pgrst.db_schemas = 'public,graphql_public,dentia';

create table if not exists dentia.clinics (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) >= 2),
  slug text not null unique,
  whatsapp text,
  timezone text not null default 'America/Sao_Paulo',
  horario_padrao jsonb not null default '{"dias":[1,2,3,4,5],"inicio":"08:00","fim":"18:00"}'::jsonb,
  duracao_padrao_consulta int not null default 30 check (duracao_padrao_consulta between 5 and 480),
  status text not null default 'ativa' check (status in ('ativa','pausada')),
  created_at timestamptz not null default now()
);

create table if not exists dentia.clinic_members (
  id uuid primary key default gen_random_uuid(),
  clinic_id uuid not null references dentia.clinics(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','dentist','receptionist')),
  status text not null default 'ativo' check (status in ('ativo','inativo')),
  created_at timestamptz not null default now(),
  unique (clinic_id, user_id)
);

create table if not exists dentia.clinic_invites (
  id uuid primary key default gen_random_uuid(),
  clinic_id uuid not null references dentia.clinics(id) on delete cascade,
  code text not null unique,
  role text not null check (role in ('owner','dentist','receptionist')),
  expires_at timestamptz not null default (now() + interval '7 days'),
  used_at timestamptz,
  created_at timestamptz not null default now()
);

-- Auditoria: append-only. clinic_id SEM FK de propósito — o histórico
-- sobrevive à exclusão do tenant (padrão Hands).
create table if not exists dentia.audit_logs (
  id bigint generated by default as identity primary key,
  clinic_id uuid,
  actor uuid,
  action text not null,
  resource text,
  resource_id text,
  created_at timestamptz not null default now()
);

-- Grants EXPLÍCITOS (anon não ganha nada no F0; superfície pública nasce na F4)
grant usage on schema dentia to anon, authenticated, service_role;
grant select, update on dentia.clinics to authenticated;
grant select, update on dentia.clinic_members to authenticated;
grant select on dentia.clinic_invites to authenticated;
-- audit_logs: nenhum grant direto; escrita só por RPC security definer/trigger

notify pgrst, 'reload config';
notify pgrst, 'reload schema';
